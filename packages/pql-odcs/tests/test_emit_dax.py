"""Unit tests for pql_odcs.emit.dax (IR -> *.Tests.dax suites)."""

from __future__ import annotations

import pytest
from factories import contract_dict, custom, prop, schema_object

from pql_odcs.emit.dax import EmitError, assign_test_names, default_suite_prefix, render_suites
from pql_odcs.loader import load_contract
from pql_odcs.mapping import map_contract
from pql_odcs.naming import NameResolver


def _render(data: dict, env: str = "DEV", **kwargs):
    contract = load_contract(data)
    outcomes = map_contract(contract, NameResolver(contract))
    return render_suites(contract, outcomes, env=env, version="9.9.9", **kwargs)


def _marvel(**root):
    return contract_dict(
        schema=[
            schema_object(
                "MarvelFact",
                [prop("Name", required=True)],
                quality=[
                    {"metric": "rowCount", "mustBeGreaterThan": 0},
                    {"metric": "rowCount", "mustBeLessThan": 100000, "severity": "warning"},
                ],
            )
        ],
        **root,
    )


class TestSuiteNaming:
    def test_suites_carry_prefix_suite_and_environment_token(self):
        given = "a contract with schema, error, and warning rules rendered for DEV"
        should = "name suites <Prefix>.<Suite>.<ENV>.Tests and put warnings in <ENV>WARN suites"

        actual = [(f.function_name, f.file_name, f.blocking) for f in _render(_marvel(dataProduct="marvel-characters"))]

        assert actual == [
            ("MarvelCharacters.Schema.DEV.Tests", "MarvelCharacters.Schema.DEV.Tests.dax", True),
            ("MarvelCharacters.DataQuality.DEV.Tests", "MarvelCharacters.DataQuality.DEV.Tests.dax", True),
            ("MarvelCharacters.DataQuality.DEVWARN.Tests", "MarvelCharacters.DataQuality.DEVWARN.Tests.dax", False),
        ], f"{given}: {should}"

    @pytest.mark.parametrize(
        ("root", "expected"),
        [
            ({"dataProduct": "sales data-mart"}, "SalesDataMart"),
            ({"name": "Marvel Characters"}, "MarvelCharacters"),
            ({"name": "2026 orders"}, "C2026Orders"),
        ],
    )
    def test_default_prefix_comes_from_data_product_then_name(self, root, expected):
        given = f"a contract with {root}"
        should = f"derive the identifier-safe prefix {expected}"

        assert default_suite_prefix(load_contract(contract_dict(**root))) == expected, f"{given}: {should}"

    @pytest.mark.parametrize("env", ["DEV PROD", "", "dev.x"])
    def test_rejects_environment_tokens_pql_test_cannot_match(self, env):
        given = f"environment {env!r}"
        should = "raise EmitError, because pql-test matches the env as one dotted token"

        with pytest.raises(EmitError) as exc:
            _render(_marvel(), env=env)

        assert "environment" in str(exc.value), f"{given}: {should}"


class TestRendering:
    def test_header_marks_the_file_as_generated_and_model_scoped(self):
        given = "any generated suite"
        should = "start with the generated-by line and a model-scoped note"
        lines = _render(_marvel())[0].content.splitlines()

        assert (lines[0], "model-scoped" in lines[2]) == (
            "// Generated by pql-odcs 9.9.9 from <dict> — do not edit",
            True,
        ), f"{given}: {should}"

    def test_renders_calls_with_catalog_argument_order(self):
        given = "a schema suite with exists and has-columns assertions"
        should = "render a DEFINE FUNCTION with a UNION of the catalog calls, then EVALUATE it"
        schema = _render(_marvel(name="M"))[0].content

        assert schema.split("\n", 3)[3] == (
            "DEFINE\n"
            "\tFUNCTION M.Schema.DEV.Tests = () =>\n"
            "\t\tUNION (\n"
            '\t\t\tPQL.Assert.Tbl.ShouldExist("ODCS marvel-contract MarvelFact.exists: MarvelFact exists", "MarvelFact"),\n'
            '\t\t\tPQL.Assert.Tbl.ShouldHaveColumns("ODCS marvel-contract MarvelFact.columns: MarvelFact has columns Name", "MarvelFact", "Name")\n'
            "\t\t)\n"
            "\n"
            "EVALUATE M.Schema.DEV.Tests()\n"
        ), f"{given}: {should}"

    def test_single_assertion_suite_has_no_union(self):
        given = "a suite with one assertion"
        should = "call it directly, because DAX UNION needs two tables"
        data = contract_dict(name="M", schema=[schema_object("T", quality=[{"metric": "rowCount", "mustBe": 3}])])
        quality = _render(data)[1].content

        assert "UNION" not in quality and "PQL.Assert.Tbl.ShouldHaveRowCount(" in quality, f"{given}: {should}"

    def test_threshold_and_table_follow_the_catalog_order(self):
        given = "rowCount mustBe 3 and mustBeGreaterThan 5"
        should = "put the table before the count, and the threshold before the table"
        data = contract_dict(
            name="M",
            schema=[
                schema_object(
                    "T", quality=[{"metric": "rowCount", "mustBe": 3}, {"metric": "rowCount", "mustBeGreaterThan": 5}]
                )
            ],
        )
        quality = _render(data)[1].content

        assert (
            "ShouldHaveRowCount(\"ODCS marvel-contract T.quality[0]: T rowCount mustBe 3\", 'T', 3)" in quality,
            "ShouldHaveMoreRowsThan(\"ODCS marvel-contract T.quality[1]: T rowCount mustBeGreaterThan 5\", 5, 'T')"
            in quality,
        ) == (True, True), f"{given}: {should}"

    def test_names_and_strings_are_dax_escaped(self):
        given = "a table and column whose model names contain quotes and brackets, and a quoted description"
        should = "double the quote, bracket, and string delimiters"
        data = contract_dict(
            name="M",
            schema=[
                schema_object(
                    "t",
                    [prop("c", required=True, customProperties=custom(pbiColumn="Size [cm]"))],
                    customProperties=custom(pbiTable="Bob's Table"),
                    quality=[{"metric": "rowCount", "mustBe": 1, "description": 'Has "one" row'}],
                )
            ],
        )
        quality = _render(data)[1].content

        assert (
            "'Bob''s Table'[Size [cm]]]" in quality,
            '"ODCS marvel-contract t.quality[0]: Has ""one"" row"' in quality,
        ) == (
            True,
            True,
        ), f"{given}: {should}"

    def test_output_is_deterministic_with_lf_line_endings(self):
        given = "the same contract rendered twice"
        should = "produce identical text with LF line endings only"
        first, second = _render(_marvel()), _render(_marvel())

        assert ([f.content for f in first] == [f.content for f in second], any("\r" in f.content for f in first)) == (
            True,
            False,
        ), f"{given}: {should}"


class TestTestNames:
    def test_shared_assertion_is_named_after_its_first_rule(self):
        given = "primaryKey and unique on the same column (one shared assertion)"
        should = "name the single test after the first rule"
        contract = load_contract(contract_dict(schema=[schema_object("D", [prop("ID", primaryKey=True, unique=True)])]))
        outcomes = map_contract(contract, NameResolver(contract))

        names = sorted(assign_test_names(contract, outcomes).values())

        assert "ODCS marvel-contract D.ID.primaryKey: D.ID is a primary key (distinct)" in names and not [
            n for n in names if "D.ID.unique" in n
        ], f"{given}: {should}"


class TestHeaderSafety:
    def test_contract_id_cannot_break_out_of_the_header_comment(self):
        given = "a contract id containing a newline followed by DAX"
        should = "keep the whole header on // comment lines so no injected DAX runs"
        data = _marvel()
        data["id"] = 'c1\nEVALUATE ROW("x", 1)\n//'

        content = _render(data)[0].content

        header = content.split("DEFINE", 1)[0]
        assert all(line.startswith("//") for line in header.splitlines()), f"{given}: {should}\n{header}"
