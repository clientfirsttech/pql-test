"""Python API shared by the ``pql-odcs`` CLI, ``pql-test contract``, and adapters."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from pql_odcs import __version__
from pql_odcs.catalog import DEFAULT_PQL_ASSERT, Catalog, catalog_for
from pql_odcs.emit.dax import (
    GENERATED_MARKER,
    SUITE_ORDER,
    WARN_SUFFIX,
    SuiteFile,
    default_suite_prefix,
    generated_owner,
    header_safe,
    render_suites,
)
from pql_odcs.ir import RuleOutcome
from pql_odcs.loader import Contract, ContractSource, load_contract
from pql_odcs.mapping import map_contract
from pql_odcs.naming import NameResolver
from pql_odcs.pbip import require_semantic_model_dir


class GenerateError(Exception):
    """Generation would overwrite a file pql-odcs did not create."""


@dataclass(frozen=True)
class Plan:
    """A loaded contract with every rule mapped."""

    contract: Contract
    outcomes: tuple[RuleOutcome, ...]
    names: NameResolver
    closed_schema: bool = False
    catalog: Catalog = field(default_factory=catalog_for)


@dataclass(frozen=True)
class GenerateResult:
    files: list[SuiteFile]
    target_dir: Path | None = None
    written: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


def plan_contract(
    source: ContractSource | Contract,
    *,
    closed_schema: bool = False,
    pql_assert: str = DEFAULT_PQL_ASSERT,
) -> Plan:
    """Load (unless already loaded) and map a contract.

    Args:
        source: YAML path, parsed dict, or a ``Contract``.
        closed_schema: also forbid columns the contract does not list.
        pql_assert: PQL.Assert version to target, ``"0.7"`` (default) or ``"0.8"``.

    Raises:
        CatalogError: *pql_assert* is not a bundled version.
    """
    contract = source if isinstance(source, Contract) else load_contract(source)
    names = NameResolver(contract)
    catalog = catalog_for(pql_assert)
    outcomes = tuple(map_contract(contract, names, closed_schema=closed_schema, catalog=catalog))
    return Plan(contract, outcomes, names, closed_schema, catalog)


def render(plan: Plan, *, env: str, suite_prefix: str | None = None, version: str = __version__) -> list[SuiteFile]:
    return render_suites(
        plan.contract, plan.outcomes, env=env, suite_prefix=suite_prefix, catalog=plan.catalog, version=version
    )


def _owner(path: Path) -> str | None:
    """Contract id that generated *path*, ``""`` for an unknown generated file, None if not generated."""
    with path.open(encoding="utf-8", errors="replace") as fh:
        first, second = fh.readline(), fh.readline()
    if not first.startswith(GENERATED_MARKER):
        return None
    return generated_owner(second) or ""


def _possible_suite_names(prefix: str, env: str) -> set[str]:
    return {f"{prefix}.{s}.{e}.Tests.dax" for s in SUITE_ORDER for e in (env, f"{env}{WARN_SUFFIX}")}


def generate(
    plan: Plan,
    model_path: str | Path,
    *,
    env: str,
    suite_prefix: str | None = None,
    force: bool = False,
    version: str = __version__,
) -> GenerateResult:
    """Render the plan and write ``*.Tests.dax`` files into the PBIP model's ``DAXQueries/``.

    Suites this contract generated earlier that no longer have rules are removed. A file
    that is hand-written, or was generated from a different contract (same suite prefix),
    is never overwritten unless *force* is set, and never removed.

    Raises:
        ModelPathError: *model_path* is not a PBIP model folder.
        GenerateError: a target file is not this contract's and *force* is False.
    """
    files = render(plan, env=env, suite_prefix=suite_prefix, version=version)
    target_dir = require_semantic_model_dir(model_path) / "DAXQueries"
    targets = [target_dir / f.file_name for f in files]
    me = header_safe(plan.contract.id)
    hand_written = [t for t in targets if t.exists() and _owner(t) is None]
    foreign = [t for t in targets if t.exists() and _owner(t) not in (None, me)]
    if hand_written and not force:
        listed = ", ".join(t.name for t in hand_written)
        raise GenerateError(f"Refusing to overwrite file(s) not generated by pql-odcs: {listed}. Pass --force.")
    if foreign and not force:
        listed = ", ".join(f"{t.name} (contract {_owner(t) or '?'})" for t in foreign)
        raise GenerateError(
            f"Refusing to overwrite suite(s) generated from another contract: {listed}. "
            "Pass a distinct --suite-prefix, or --force."
        )
    target_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for f, path in zip(files, targets):
        with path.open("w", encoding="utf-8", newline="\n") as fh:  # Path.write_text(newline=) is 3.10+
            fh.write(f.content)
        written.append(path)
    keep = {t.name for t in targets}
    prefix = suite_prefix or default_suite_prefix(plan.contract)
    removed = []
    for name in sorted(_possible_suite_names(prefix, env) - keep):
        stale = target_dir / name
        if stale.exists() and _owner(stale) == me:
            stale.unlink()
            removed.append(stale)
    return GenerateResult(files, target_dir, written, removed)
