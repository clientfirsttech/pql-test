"""Python API shared by the ``pql-odcs`` CLI, ``pql-test contract``, and adapters."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path

from pql_odcs import __version__
from pql_odcs.emit.dax import GENERATED_MARKER, SUITE_ORDER, WARN_SUFFIX, SuiteFile, default_suite_prefix, render_suites
from pql_odcs.ir import RuleOutcome
from pql_odcs.loader import Contract, ContractSource, load_contract
from pql_odcs.mapping import map_contract
from pql_odcs.naming import NameResolver, load_sidecar
from pql_odcs.pbip import require_semantic_model_dir


class GenerateError(Exception):
    """Generation would overwrite a file pql-odcs did not create."""


@dataclass(frozen=True)
class Plan:
    """A loaded contract with every rule mapped."""

    contract: Contract
    outcomes: tuple[RuleOutcome, ...]
    names: NameResolver
    closed_schema: bool = False


@dataclass(frozen=True)
class GenerateResult:
    files: list[SuiteFile]
    target_dir: Path | None = None
    written: list[Path] = field(default_factory=list)
    removed: list[Path] = field(default_factory=list)


def plan_contract(
    source: ContractSource | Contract,
    *,
    mapping: str | Path | Mapping | None = None,
    closed_schema: bool = False,
) -> Plan:
    """Load (unless already loaded) and map a contract.

    Args:
        source: YAML path, parsed dict, or a ``Contract``.
        mapping: sidecar mapping file path, or an already-parsed sidecar dict.
        closed_schema: also forbid columns the contract does not list.
    """
    contract = source if isinstance(source, Contract) else load_contract(source)
    sidecar = load_sidecar(mapping) if isinstance(mapping, (str, Path)) else mapping
    names = NameResolver(contract, sidecar)
    outcomes = tuple(map_contract(contract, names, closed_schema=closed_schema))
    return Plan(contract, outcomes, names, closed_schema)


def render(plan: Plan, *, env: str, suite_prefix: str | None = None, version: str = __version__) -> list[SuiteFile]:
    return render_suites(plan.contract, plan.outcomes, env=env, suite_prefix=suite_prefix, version=version)


def _is_generated(path: Path) -> bool:
    with path.open(encoding="utf-8", errors="replace") as fh:
        return fh.readline().startswith(GENERATED_MARKER)


def _possible_suite_names(prefix: str, env: str) -> set[str]:
    return {f"{prefix}.{s}.{e}.Tests.dax" for s in SUITE_ORDER for e in (env, f"{env}{WARN_SUFFIX}")}


def generate(
    plan: Plan,
    model_path: str | Path,
    *,
    env: str,
    suite_prefix: str | None = None,
    force: bool = False,
    version: str = __version__,
) -> GenerateResult:
    """Render the plan and write ``*.Tests.dax`` files into the PBIP model's ``DAXQueries/``.

    Generated suites from an earlier run that no longer have rules are removed. A file
    without the generated header is never overwritten unless *force* is set.

    Raises:
        ModelPathError: *model_path* is not a PBIP model folder.
        GenerateError: a target file was not generated by pql-odcs and *force* is False.
    """
    files = render(plan, env=env, suite_prefix=suite_prefix, version=version)
    target_dir = require_semantic_model_dir(model_path) / "DAXQueries"
    targets = [target_dir / f.file_name for f in files]
    blocked = [t for t in targets if t.exists() and not _is_generated(t)]
    if blocked and not force:
        listed = ", ".join(t.name for t in blocked)
        raise GenerateError(f"Refusing to overwrite file(s) not generated by pql-odcs: {listed}. Pass --force.")
    target_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for f, path in zip(files, targets):
        with path.open("w", encoding="utf-8", newline="\n") as fh:  # Path.write_text(newline=) is 3.10+
            fh.write(f.content)
        written.append(path)
    keep = {t.name for t in targets}
    prefix = suite_prefix or default_suite_prefix(plan.contract)
    removed = []
    for name in sorted(_possible_suite_names(prefix, env) - keep):
        stale = target_dir / name
        if stale.exists() and _is_generated(stale):
            stale.unlink()
            removed.append(stale)
    return GenerateResult(files, target_dir, written, removed)
