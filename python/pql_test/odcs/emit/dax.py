"""Render IR assertions through the catalog into PQL.Assert ``*.Tests.dax`` suites."""

from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from typing import Any

from pql_test.odcs import __version__
from pql_test.odcs.catalog import Catalog, CatalogError, load_catalog
from pql_test.odcs.ir import (
    DATA_QUALITY_SUITE,
    ERROR,
    SCHEMA_SUITE,
    Assertion,
    RuleOutcome,
)
from pql_test.odcs.loader import Contract

GENERATED_MARKER = "// Generated by pql-test"
SUITE_ORDER = (SCHEMA_SUITE, DATA_QUALITY_SUITE)
WARN_SUFFIX = "WARN"
_TOKEN_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
_CONTROL_RE = re.compile(r"[\x00-\x1f\x7f\u2028\u2029]+")
_OWNER_RE = re.compile(r"^// Contract (.*) \(ODCS v[^)]*\);")


class EmitError(Exception):
    """Invalid emit options (environment token, suite prefix) or an unrenderable assertion."""


@dataclass(frozen=True)
class SuiteFile:
    """One generated ``*.Tests.dax`` file."""

    function_name: str  # e.g. "Marvel.DataQuality.DEV.Tests"
    suite: str  # SCHEMA_SUITE | DATA_QUALITY_SUITE
    blocking: bool  # False for <ENV>WARN suites (warning-severity rules)
    content: str

    @property
    def file_name(self) -> str:
        return f"{self.function_name}.dax"


def default_suite_prefix(contract: Contract) -> str:
    """PascalCase identifier from the contract's dataProduct, then name, then id."""
    source = contract.data_product or contract.name or contract.id
    words = re.findall(r"[A-Za-z0-9]+", str(source))
    prefix = "".join(w[:1].upper() + w[1:] for w in words) or "Contract"
    return prefix if prefix[0].isalpha() else f"C{prefix}"


def unique_assertions(outcomes: Iterable[RuleOutcome]) -> list[Assertion]:
    """Assertions in rule order, each shared assertion once."""
    seen: set[int] = set()
    result = []
    for outcome in outcomes:
        for a in outcome.assertions:
            if id(a) not in seen:
                seen.add(id(a))
                result.append(a)
    return result


def assign_test_names(contract: Contract, outcomes: Sequence[RuleOutcome]) -> dict[int, str]:
    """``id(assertion) -> test name``: ``ODCS <contractId> <ruleId>: <description>``, made unique."""
    names: dict[int, str] = {}
    used: dict[str, int] = {}
    for a in unique_assertions(outcomes):
        base = f"ODCS {contract.id} {a.rule_id}: {a.description}"
        used[base] = used.get(base, 0) + 1
        names[id(a)] = base if used[base] == 1 else f"{base} ({used[base]})"
    return names


def header_safe(text: str) -> str:
    """One-line text for a ``//`` header comment: control characters (CR, LF, ...) become spaces."""
    return _CONTROL_RE.sub(" ", str(text))


def generated_owner(header_line: str) -> str | None:
    """Contract id from a generated file's second header line, or None."""
    match = _OWNER_RE.match(header_line)
    return match.group(1) if match else None


def dax_string(text: str) -> str:
    return '"' + str(text).replace('"', '""') + '"'


def dax_table(name: str) -> str:
    return "'" + name.replace("'", "''") + "'"


def dax_column(table: str, column: str) -> str:
    return dax_table(table) + "[" + column.replace("]", "]]") + "]"


def dax_literal(value: Any) -> str:
    if isinstance(value, bool):
        return "TRUE()" if value else "FALSE()"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value.is_integer():
            return str(int(value))
        text = repr(value)
        return f"{value:.20f}".rstrip("0") if "e" in text else text
    return dax_string(str(value))


def _argument(source: str, a: Assertion, test_name: str, catalog: Catalog) -> str:
    target = a.target
    if source == "testName":
        return dax_string(test_name)
    if source == "tableName":
        return dax_string(target.table)
    if source == "tableRef":
        return dax_table(target.table)
    if source == "rowCount":
        return f"COUNTROWS({dax_table(target.table)})"
    if source == "columnRef":
        if target.column is None:
            raise EmitError(f"Rule {a.rule_id}: op {a.op} needs a column target.")
        return dax_column(target.table, target.column)
    if source == "keyProjection":
        columns = a.args["columns"]
        parts = ", ".join(f'"k{i}", {dax_column(target.table, c)}' for i, c in enumerate(columns, 1))
        return f"SELECTCOLUMNS({dax_table(target.table)}, {parts})"
    if source == "columnList":
        return dax_string(",".join(a.args["columns"]))
    if source in ("columnName", "dataType") and target.column is None:
        raise EmitError(f"Rule {a.rule_id}: op {a.op} needs a column target.")
    if source == "columnName":
        return dax_string(target.column)
    if source == "dataType":
        return _expected_data_type(target, a.args["types"])
    if source not in a.args:
        raise CatalogError(
            f"Catalog {catalog.name} op {a.op} expects argument {source!r}, which rule {a.rule_id} does not provide."
        )
    return dax_literal(a.args[source])


def _expected_data_type(target, types: list[str]) -> str:
    """The expected type argument: one name, or (for several) the column's own type when it is allowed.

    With several allowed types the check still compares one name, so a failure reports
    "expected <first>, actual <type>" instead of a bare TRUE/FALSE.
    """
    if len(types) == 1:
        return dax_string(types[0])
    actual = (
        f"MAXX(FILTER(INFO.VIEW.COLUMNS(), [Table] = {dax_string(target.table)} && [Name] = {dax_string(target.column)}), "
        "[DataType])"
    )
    branches = ", ".join(f"{dax_string(t)}, {dax_string(t)}" for t in types[1:])
    return f"SWITCH({actual}, {branches}, {dax_string(types[0])})"


def render_call(a: Assertion, test_name: str, catalog: Catalog) -> str:
    spec = catalog.op(a.op)
    return f"{spec.fn}({', '.join(_argument(s, a, test_name, catalog) for s in spec.args)})"


def _validate_token(value: str, what: str) -> None:
    if not _TOKEN_RE.match(value or ""):
        raise EmitError(f"Invalid {what} {value!r}: use letters, digits, and _ (starting with a letter).")


def _suite_content(function_name: str, calls: list[str], header: list[str]) -> str:
    if len(calls) == 1:
        body = [f"\t\t{calls[0]}"]
    else:
        body = ["\t\tUNION (", *(f"\t\t\t{c}," for c in calls[:-1]), f"\t\t\t{calls[-1]}", "\t\t)"]
    lines = [*header, "DEFINE", f"\tFUNCTION {function_name} = () =>", *body, "", f"EVALUATE {function_name}()"]
    return "\n".join(lines) + "\n"


def render_suites(
    contract: Contract,
    outcomes: Sequence[RuleOutcome],
    *,
    env: str,
    suite_prefix: str | None = None,
    catalog: Catalog | None = None,
    version: str = __version__,
) -> list[SuiteFile]:
    """Render one suite per (suite, severity) that has assertions, in a stable order."""
    _validate_token(env, "environment")
    prefix = suite_prefix or default_suite_prefix(contract)
    _validate_token(prefix, "suite prefix")
    catalog = catalog or load_catalog()
    names = assign_test_names(contract, outcomes)
    assertions = unique_assertions(outcomes)
    files = []
    for suite in SUITE_ORDER:
        for blocking in (True, False):
            group = [a for a in assertions if a.suite == suite and (a.severity == ERROR) == blocking]
            if not group:
                continue
            env_token = env if blocking else f"{env}{WARN_SUFFIX}"
            function_name = f"{prefix}.{suite}.{env_token}.Tests"
            header = [
                f"{GENERATED_MARKER} {version} from {header_safe(contract.source)} — do not edit",
                (
                    f"// Contract {header_safe(contract.id)} (ODCS v{contract.api_version}); "
                    f"targets {catalog.library} >= {catalog.min_version}"
                ),
                (
                    "// Results are model-scoped: they test the semantic model's data "
                    "(filters, RLS, incremental refresh apply), not the source system."
                ),
            ]
            if not blocking:
                header.append("// Warning-severity rules: run separately; failures here should not fail the build.")
            calls = [render_call(a, names[id(a)], catalog) for a in group]
            files.append(SuiteFile(function_name, suite, blocking, _suite_content(function_name, calls, header)))
    return files
